package P03;
public class AssignmentOperatorExample {
    public static void main(){
        int result = 0;
        result += 10;
        System.out.println("result = "+ result);
        result -= 5;
        System.out.println("result = "+ result);
        result *= 3;
        System.out.println("result = "+ result);
        result /= 5;
        System.out.println("result = "+ result);
        result %= 3;
        System.out.println("result = "+ result);
    }
}
